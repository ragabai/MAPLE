"""Automated results report (spec §11) and the summary used by the manuscript. All statements are conditional on
computed statistics: significance language is used only when the Holm-adjusted p-value is below 0.05."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from maple.reporting import analysis as A
from maple.reporting import stats_pipeline as SP
from maple.utils import PROJECT_ROOT, write_json

ALPHA = 0.05
PRACTICAL = 0.01  # |median relative difference| below 1% = practically negligible


def fmt_p(p) -> str:
    if p is None or (isinstance(p, float) and np.isnan(p)):
        return "n/a"
    return "< 0.001" if p < 1e-3 else f"{p:.3f}"


def verdict(rec: dict, better: str, worse: str) -> str:
    """Plain-language comparison for a _pair() record (a = better candidate).

    Direction: sign of the median relative difference, tie-broken by the rank-biserial correlation.
    Significance: the family-wise Holm-adjusted p-value when available (pre-registered families), else raw p.
    """
    if not rec:
        return f"no paired data for {better} vs {worse}"
    md = rec.get("median_diff", np.nan)
    sign = np.sign(md) if md != 0 else np.sign(rec.get("r_rb", 0.0))
    direction = "lower" if sign > 0 else ("higher" if sign < 0 else "equal")
    p_use = rec.get("p_holm_family", rec.get("p", np.nan))
    sig = p_use < ALPHA
    size = "practically negligible" if abs(md) < PRACTICAL else f"a median relative difference of {abs(md) * 100:.1f}%"
    ptxt = (f"Holm-adjusted p = {fmt_p(p_use)} within a family of {rec['family_size']} tests"
            if "p_holm_family" in rec else f"Wilcoxon p = {fmt_p(p_use)}")
    s = (f"{better} had {direction} error than {worse} ({size}; W/L/T = {rec['wins']}/{rec['losses']}/{rec['ties']}, "
         f"N = {rec['N']}, {ptxt}, r_rb = {rec['r_rb']:.2f})")
    s += "; the difference is statistically significant" if sig else "; the difference is not statistically significant"
    return s + "."


def size_class_breakdown(df: pd.DataFrame, regime: int, labels: list[str]) -> pd.DataFrame:
    meta = pd.DataFrame(json.loads((PROJECT_ROOT / "experiments" / "data" / "metadata.json").read_text())).set_index("name")
    tab = A.per_dataset(df, "nrmse", regime, complete=True, labels=labels)
    tab["size"] = meta.loc[tab.index, "size_class"].to_numpy()
    return tab.groupby("size").mean()


def family_breakdown(sdf: pd.DataFrame, labels: list[str]) -> pd.DataFrame:
    smooth = {"linear", "polynomial", "exponential", "logarithmic", "power_law", "rational", "trigonometric", "rbf",
              "logistic", "michaelis_menten", "damped_oscillator", "logistic_ode", "lotka_volterra", "physics"}
    inter = {"interaction", "interaction3", "conditional", "discontinuous", "piecewise", "voronoi", "mixed_regime"}
    d = sdf[sdf.label.isin(labels)].copy()
    tasks = d[["suite", "task", "family_task"]].drop_duplicates(["suite", "task"])
    d["group"] = d.family_task.map(lambda f: "smooth" if f in smooth else ("interaction/irregular" if f in inter else "held-out family"))
    hi = d.noise_rel >= d.noise_rel.median()
    d.loc[hi, "noise_group"] = "high noise"
    d.loc[~hi, "noise_group"] = "low noise"
    g1 = d.groupby(["group", "label"]).nrmse.mean().unstack("label")
    g2 = d.groupby(["noise_group", "label"]).nrmse.mean().unstack("label")
    del tasks
    return pd.concat([g1, g2])


def build_report(stats: dict, df: pd.DataFrame, sdf: pd.DataFrame) -> tuple[str, dict]:
    L: list[str] = ["# Automated Results Report", "",
                    "Generated by `scripts/generate_report.py` from `experiments/raw/*.jsonl` and "
                    "`results/statistics/statistics.json`. Statements of significance use two-sided Wilcoxon "
                    "signed-rank tests with the unit and correction stated; |median relative difference| < 1% is "
                    "called practically negligible.", ""]
    summary: dict = {"real": {}, "synthetic": {}, "ablation": {}}
    # ------------------------------------------------------------------ real data
    for reg, r in stats.get("real", {}).items():
        if "avg_rank_full" not in r or not r["avg_rank_full"]:
            continue
        ranks = pd.Series(r["avg_rank_full"]).sort_values()
        full = pd.DataFrame(r["nrmse_per_dataset"]).dropna()
        best = ranks.index[0]
        L += [f"## Real-data benchmark, n_train = {reg}", "",
              f"**What happened.** {len(full)} datasets had results for all {len(ranks)} methods. Mean ranks (lower "
              f"is better): " + ", ".join(f"{k} {v:.2f}" for k, v in ranks.head(8).items()) + ".", ""]
        L.append(f"**Best method.** {best} had the best mean rank ({ranks.iloc[0]:.2f}).")
        if "friedman" in r:
            f = r["friedman"]
            L.append(f"Friedman test over the main comparison set (k = {f['k']}, N = {f['N']}): χ²({f['df']}) = "
                     f"{f['chi2']:.1f}, p = {fmt_p(f['p'])}; Nemenyi critical difference = {r['nemenyi_cd']:.2f}.")
        rq = r.get("rq", {})
        L += ["", "**Key comparisons (RQ4–RQ6).**", ""]
        pairs = [("RQ4_A_vs_P0", "PFN-A", "PFN-SCM"), ("RQ4_D_vs_P0", "PFN-D", "PFN-SCM"),
                 ("RQ1_real_D_vs_A", "PFN-D", "PFN-A"), ("RQ2_real_C_vs_B", "PFN-C", "PFN-B"),
                 ("RQ5_F_vs_PFN-D", "MAPLE-F", "PFN-D"), ("RQ5_F_vs_Stack(experts)", "MAPLE-F", "Stack(experts)"),
                 ("RQ5_F_vs_Stack(PFN-D)", "MAPLE-F", "Stack(PFN-D)"), ("RQ5_F_vs_MAPLE-E", "MAPLE-F", "MAPLE-E"),
                 ("RQ6_F_vs_CatBoost-T", "MAPLE-F", "CatBoost-T"), ("RQ6_F_vs_XGBoost-T", "MAPLE-F", "XGBoost-T"),
                 ("RQ6_F_vs_LightGBM-T", "MAPLE-F", "LightGBM-T")]
        for k, a, b in pairs:
            L.append(f"- {verdict(rq.get(k, {}), a, b)}")
        ex = r.get("exploratory", {})
        if ex:
            L += ["", "**Exploratory (not pre-registered; raw p).**", ""]
            for k, a, b in (("StackPFN_vs_StackExperts", "Stack(PFN-D)", "Stack(experts)"), ("E_vs_F", "MAPLE-E", "MAPLE-F")):
                L.append(f"- {verdict(ex.get(k, {}), a, b)}")
        if "MAPLE-F" in full and len(full):
            classical = [c for c in full.columns if not c.startswith(("PFN", "MAPLE", "Stack(PFN", "TabPFN", "TabICL"))]
            best_cls = full[classical].min(axis=1)
            ben = full.index[full["MAPLE-F"] < best_cls].tolist()
            notb = full.index[full["MAPLE-F"] >= best_cls].tolist()
            L += ["", f"**Datasets that benefited.** MAPLE-F beat the best classical method on {len(ben)}/{len(full)} "
                  f"datasets: {', '.join(ben) if ben else 'none'}.",
                  f"**Datasets that did not benefit.** {', '.join(notb) if notb else 'none'}."]
            summary["real"][reg] = {"n_datasets": len(full), "best": best, "ranks": ranks.round(3).to_dict(),
                                    "benefited": ben, "not_benefited": notb,
                                    "maple_mean_nrmse": float(full["MAPLE-F"].mean()),
                                    "best_classical_mean_nrmse": float(best_cls.mean()),
                                    "rq": {k: {kk: (float(vv) if isinstance(vv, (int, float, np.floating)) else vv)
                                               for kk, vv in v.items()} for k, v in rq.items() if v}}
        if len(df):
            try:
                sc = size_class_breakdown(df, int(reg), [l for l in SP.MAIN_SET if l in set(df.label)])
                L += ["", "**By dataset size class (mean NRMSE).**", "", sc.round(3).to_markdown()]
                summary["real"].setdefault(reg, {})["size_class"] = sc.round(4).to_dict()
            except Exception as e:  # pragma: no cover
                L.append(f"(size-class breakdown unavailable: {e})")
        L.append("")
    # ------------------------------------------------------------------ synthetic
    syn = stats.get("synthetic", {})
    if syn:
        gap = pd.DataFrame(syn["nrmse_generalization_gap"]).T
        L += ["## Synthetic generalisation (ID vs structural OOD)", "",
              "**What happened.** Mean NRMSE on in-distribution and pooled out-of-distribution suites:", "",
              gap.round(3).sort_values("ood").to_markdown(), ""]
        rq1 = syn.get("RQ1_nrmse", {})
        L += [f"- RQ1 (ID): {verdict(rq1.get('id', {}), 'PFN-D', 'PFN-A')}",
              f"- RQ1 (pooled OOD): {verdict(rq1.get('pooled_ood', {}), 'PFN-D', 'PFN-A')}"]
        for s, rec in rq1.get("per_suite", {}).items():
            if rec:
                L.append(f"  - {s}: median rel. diff {rec['median_diff'] * 100:.1f}%, Holm-adjusted p across suites = "
                         f"{fmt_p(rec.get('p_holm_across_suites'))}")
        rq2 = syn.get("RQ2", {})
        rq2f = syn.get("RQ2_nrmse_f", {})
        L += [f"- RQ2 (all tasks, NRMSE, pre-registered): {verdict(rq2.get('all', {}), 'PFN-C', 'PFN-B')}",
              f"- RQ2 (high-noise tasks): {verdict(rq2.get('high_noise', {}), 'PFN-C', 'PFN-B')}",
              f"- RQ2 (low-noise tasks): {verdict(rq2.get('low_noise', {}), 'PFN-C', 'PFN-B')}",
              f"- RQ2 (all tasks, excess NRMSE vs noise-free target, supplementary): "
              f"{verdict(rq2f.get('all', {}), 'PFN-C', 'PFN-B')}"]
        rq4 = syn.get("RQ4_synthetic_nrmse", {})
        L += [f"- Prior comparison (ID): {verdict(rq4.get('id_A_vs_P0', {}), 'PFN-A', 'PFN-SCM')}",
              f"- Prior comparison (OOD): {verdict(rq4.get('ood_A_vs_P0', {}), 'PFN-A', 'PFN-SCM')}"]
        rq3 = syn.get("RQ3", {})
        if rq3:
            L += ["", "**Does disagreement track error (RQ3)?** Task-level Spearman correlation between the "
                  "label-free gap Δ̄ and the PFN's excess error:", ""]
            for l, r3 in rq3.items():
                L.append(f"- {l}: ρ = {r3['spearman']:.2f} (95% CI [{r3['ci'][0]:.2f}, {r3['ci'][1]:.2f}], n = {r3['n']}); "
                         f"committee better than the PFN on {r3['frac_committee_better'] * 100:.0f}% of tasks "
                         f"(the regime where Prop. 4 makes Δ̄ informative); for comparison ρ(loss, excess) = "
                         f"{r3['spearman_loss_vs_excess']:.2f}.")
        if len(sdf):
            fb = family_breakdown(sdf, ["PFN-A", "PFN-D", "ExtraTrees", "CatBoost", "PFN-SCM"])
            L += ["", "**By structure and noise (mean NRMSE).**", "", fb.round(3).to_markdown(), ""]
            summary["synthetic"]["breakdown"] = fb.round(4).to_dict()
        r3r = syn.get("RQ3_real", {})
        if r3r:
            L.append(f"- Real data (unit = dataset, n = {r3r['n_datasets']}): Spearman(gap, PFN test MSE) = "
                     f"{r3r['spearman_datasets']:.2f} (95% CI [{r3r['ci'][0]:.2f}, {r3r['ci'][1]:.2f}]); median "
                     f"within-dataset ρ = {r3r['median_within_dataset_spearman']:.2f}; committee more accurate than "
                     f"the PFN on {r3r['frac_committee_better'] * 100:.0f}% of datasets.")
        summary["synthetic"].update({"gap": gap.round(4).to_dict(), "RQ1": rq1, "RQ2": rq2, "RQ2_nrmse_f": rq2f,
                                     "RQ3": rq3, "RQ3_real": r3r, "RQ4": rq4})
    # ------------------------------------------------------------------ ablations
    ab = stats.get("ablation", {})
    if ab:
        L += ["## Ablations and sensitivity (one-factor changes from PFN-D, seed 0)", ""]
        for n, rec in sorted(ab.items()):
            s = rec.get("synthetic", {})
            if s:
                ch = s["delta_vs_ref"] * 100
                L.append(f"- {n}: median relative NRMSE change vs PFN-D on synthetic tasks {ch:+.1f}% "
                         f"(positive = worse; raw p = {fmt_p(s['p'])})"
                         + (f"; real n=512 {rec['real512']['delta_vs_ref'] * 100:+.1f}% (raw p = {fmt_p(rec['real512']['p'])})"
                            if rec.get("real512") else ""))
        summary["ablation"] = ab
        L.append("")
    L += ["## Limitations (automatically collected)", "",
          "- Pretraining used ~15k steps of a ~4M-parameter PFN on shared GPUs; production tabular foundation models "
          "train orders of magnitude longer. Conclusions concern the controlled equal-budget comparison.",
          "- Real datasets with more than 32 features are reduced by train-only mutual-information selection for the "
          "PFN (not for the baselines); training sets above 1024 rows use context bagging.",
          "- Ablation and sensitivity runs use a single pretraining seed.",
          "- Noise level in the generator is independent of the cell, which limits the cell-level advantage that "
          "Prop. 4(a) predicts for disagreement over loss scores (pilot report).", ""]
    return "\n".join(L) + "\n", summary


def write(stats, df, sdf, adaptation: dict | None = None) -> dict:
    text, summary = build_report(stats, df, sdf)
    if adaptation:
        summary["adaptation"] = adaptation
    out = PROJECT_ROOT / "results" / "reports"
    out.mkdir(parents=True, exist_ok=True)
    (out / "results_report.md").write_text(text, encoding="utf-8")
    write_json(PROJECT_ROOT / "results" / "summary.json", summary)
    return summary
